"""Strokes -> G-code.

Each stroke is one extrusion run. Straight runs of cells collapse into single
G1 moves. Extrusion gives every cell the same volume: segment E = L w h / (pi (d/2)^2),
plus half a cell's worth at each open-stroke end, since cell-centre paths stop
half a cell short of the part edge.
"""
from __future__ import annotations

import io
from dataclasses import dataclass

import numpy as np

from rltp.config import Printer
from rltp.cover.cover import get_pieces
from rltp.part import PartState


@dataclass
class GcodeStats:
    layers: int
    strokes: int
    moves: int
    filament_mm: float
    print_mm: float
    travel_mm: float
    retractions: int


def collapse(xy: np.ndarray) -> np.ndarray:
    """Keep the first, last and every corner point of a polyline on the grid."""
    if len(xy) <= 2:
        return xy
    d = np.diff(xy, axis=0)
    d = np.round(d / np.maximum(np.linalg.norm(d, axis=1, keepdims=True), 1e-12), 6)
    keep = np.ones(len(xy), bool)
    keep[1:-1] = np.any(d[1:] != d[:-1], axis=1)
    return xy[keep]


def part_offset(part: PartState, pr: Printer) -> np.ndarray:
    """Translation placing the part's XY footprint centre at the bed centre."""
    xs, ys = [], []
    for L in part.layers:
        cells = np.flatnonzero(L.flat_mask)
        x, y = L.frame.cell_xy(cells, L.W)
        xs += [x.min(), x.max()]
        ys += [y.min(), y.max()]
    c = np.array([(min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2])
    return np.asarray(pr.bed_center, float) - c


def layer_strokes_world(L, ev, offset):
    """[(xy points incl. loop closure, is_loop, single)] in print order, world + offset."""
    pc = get_pieces(L)
    out = []
    for pid in ev.timing.order:
        cells = pc.cells[pid]
        loop = bool(pc.is_loop[pid])
        seq = np.append(cells, cells[0]) if loop else cells
        x, y = L.frame.cell_xy(seq, L.W)
        out.append((np.stack([x, y], 1) + offset, loop, len(cells) == 1))
    return out


def write_gcode(path, part: PartState, pr: Printer, header: str = "") -> GcodeStats:
    off = part_offset(part, pr)
    w, d_f = pr.bead_width, pr.filament_diameter
    area = np.pi * (d_f / 2) ** 2
    p = pr.bead_width
    buf = io.StringIO()
    W = buf.write
    fmt = {"bed_temp": pr.bed_temp, "nozzle_temp": pr.nozzle_temp}
    W(f"; generated by rltp\n; printer: {pr.name}\n")
    for line in header.splitlines():
        W(f"; {line}\n")
    W(f"; layer_height = {pr.layer_height}\n; first_layer_height = {pr.first_layer_height}\n")
    W(f"; extrusion_width = {w}\n; layers = {len(part.layers)}\n")
    W(pr.start_gcode.format(**fmt))
    W("G21 ; mm\nG90 ; absolute XYZ\nM83 ; relative E\n")
    retracted = False
    pos = None
    n_moves = n_str = n_ret = 0
    fil = pmm = tmm = 0.0
    f_travel = pr.travel_speed * 60
    f_retract = pr.retract_speed * 60
    f_z = pr.z_speed * 60

    def retract():
        nonlocal retracted, n_ret
        if not retracted and pr.retract_length > 0:
            W(f"G1 E{-pr.retract_length:.5f} F{f_retract:.0f}\n")
            retracted = True
            n_ret += 1

    def unretract():
        nonlocal retracted
        if retracted and pr.retract_length > 0:
            W(f"G1 E{pr.retract_length:.5f} F{f_retract:.0f}\n")
        retracted = False

    for k, (L, ev) in enumerate(zip(part.layers, part.evals)):
        h = L.h
        speed = (pr.first_layer_speed if L.first else pr.print_speed) * 60
        e_per_mm = w * h / area
        W(f";LAYER_CHANGE\n;Z:{L.z:.3f}\n;HEIGHT:{h:.3f}\n")
        if k == 1:
            W(f"M106 S{pr.fan_speed}\n")
        retract()
        W(f"G1 Z{L.z:.3f} F{f_z:.0f}\n")
        W(f";TYPE:Solid infill\n;WIDTH:{w:.3f}\n")
        for xy, loop, single in layer_strokes_world(L, ev, off):
            n_str += 1
            if single:
                c = xy[0]
                pts = np.array([c - [p / 4, 0], c + [p / 4, 0]])
            else:
                pts = collapse(xy)
            start = pts[0]
            dist = np.inf if pos is None else float(np.hypot(*(start - pos)))
            if dist > 1e-9:
                hop = dist > 2 * p
                if hop:
                    retract()
                    if pr.z_hop > 0:
                        W(f"G1 Z{L.z + pr.z_hop:.3f} F{f_z:.0f}\n")
                W(f"G0 X{start[0]:.3f} Y{start[1]:.3f} F{f_travel:.0f}\n")
                if hop and pr.z_hop > 0:
                    W(f"G1 Z{L.z:.3f} F{f_z:.0f}\n")
                if np.isfinite(dist):
                    tmm += dist
            unretract()
            seg = np.diff(pts, axis=0)
            lens = np.linalg.norm(seg, axis=1)
            E = lens * e_per_mm
            if single:
                E[:] = p * e_per_mm
            elif not loop:
                E[0] += 0.5 * p * e_per_mm
                E[-1] += 0.5 * p * e_per_mm
            for q, e in zip(pts[1:], E):
                W(f"G1 X{q[0]:.3f} Y{q[1]:.3f} E{e:.5f} F{speed:.0f}\n")
                n_moves += 1
            fil += float(E.sum())
            pmm += float(lens.sum())
            pos = pts[-1]
    retract()
    W(pr.end_gcode.format(**fmt))
    with open(path, "w") as f:
        f.write(buf.getvalue())
    return GcodeStats(len(part.layers), n_str, n_moves, fil, pmm, tmm, n_ret)
